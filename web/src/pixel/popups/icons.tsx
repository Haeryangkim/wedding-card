export type PixelIconName = keyof typeof ICONS

export function PixelIcon({ name, size = 16 }: { name: PixelIconName; size?: number }) {
  const rows = ICONS[name]
  const rects: { x: number; y: number; w: number }[] = []
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      if (row[x] !== '#') {
        x++
        continue
      }
      let w = 1
      while (x + w < row.length && row[x + w] === '#') w++
      rects.push({ x, y, w })
      x += w
    }
  })
  return (
    <svg
      className="pxicon"
      viewBox="0 0 12 12"
      width={size}
      height={size}
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {rects.map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width={r.w} height={1} fill="currentColor" />
      ))}
    </svg>
  )
}
